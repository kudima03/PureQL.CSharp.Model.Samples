/// <summary>
/// Selects item_id and item_order_id (as order_id) from
/// schema_with_foreign_keys.order_items joined to schema_with_foreign_keys.products on
/// item_product_id, with the line total (product_price times item_qty), its running total
/// over the items of the order in item_id order (a frame from the start of the
/// partition), the row_number of the item by line total, largest first, in its order, its
/// share of the total of all line totals (guarded with nullIfEqual), and a label made of
/// # and the item_qty, ordered by the select columns order_id, position, running_total
/// (descending), share and label, then by item_id.
/// </summary>
public sealed record SortingBySelectWindowColumnsQuery
{
