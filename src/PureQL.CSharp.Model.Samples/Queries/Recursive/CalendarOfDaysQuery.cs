/// <summary>
/// Selects a row for each day from 2024-05-31 to 2024-06-07 with its orders and revenue:
/// an inline rows subquery first_day holds the first date, a recursive subquery days is
/// seeded from it and adds one day with dateAddDays while day is before 2024-06-07
/// (maxDepth 366), and a grouped subquery daily counts the orders of
/// schema_with_foreign_keys.orders and sums order_total per placed_on. The main query
/// reads days, left joins daily on day, and selects day with the coalesced count and
/// revenue (an integer 0 widened to decimal), ordered by day.
/// </summary>
public sealed record CalendarOfDaysQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            subqueries:
            [
                new SubqueryRows(
                    "first_day",
                    [
                        [new RowItem("day", new LiteralDate(new DateOnly(2024, 5, 31)))],
                    ]
                ),
                new SubqueryRecursive(
                    "days",
                    new Recursion(
                        new PlainQueryWithoutPaginationWithoutOrderBy(
                            from: new FromSubquery("first_day"),
                            select:
                            [
                                new SelectItemProjection(
                                    "day",
                                    new FieldDate("first_day", "day")
                                ),
                            ]
                        ),
                        new PlainNextQuery(
                            from: new FromSubquery("days"),
                            where: new LessThanDateRow(
                                new FieldDate("days", "day"),
                                new LiteralDate(new DateOnly(2024, 6, 7))
                            ),
                            select:
                            [
                                new SelectItemRow(
                                    "day",
                                    new DateAddDaysDateRow(
                                        new FieldDate("days", "day"),
                                        new LiteralInteger(1)
                                    )
                                ),
                            ]
                        ),
                        366
                    )
                ),
                new SubqueryQuery(
                    "daily",
                    new GroupedQueryWithoutPaginationWithoutOrderBy(
                        from: new FromEntity(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue
                        ),
                        groupBy:
                        [
                            new GroupKey(
                                "day",
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                )
                            ),
                        ],
                        select:
                        [
                            new SelectItemGroup("day", new KeyDate("day")),
                            new SelectItemGroup("orders", new CountGroup()),
                            new SelectItemGroup(
                                "revenue",
                                new SumDecimalGroup(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    )
                                )
                            ),
                        ]
                    )
                ),
            ],
            from: new FromSubquery("days"),
            joins:
            [
                new JoinSubquery(
                    JoinKind.Left,
                    "daily",
                    new EqualDateRow(
                        new FieldDate("days", "day"),
                        new FieldDate("daily", "day")
                    )
                ),
            ],
            select:
            [
                new SelectItemProjection("day", new FieldDate("days", "day")),
                new SelectItemProjection(
                    "orders",
                    new CoalesceIntegerProjection([
                        new FieldIntegerNullable("daily", "orders"),
                        new LiteralInteger(0),
                    ])
                ),
                new SelectItemProjection(
                    "revenue",
                    new CoalesceDecimalProjection([
                        new FieldDecimalNullable("daily", "revenue"),
                        new LiteralInteger(0),
                    ])
                ),
            ],
            orderBy: [new OrderItemProjectionExpression(new FieldDate("days", "day"))]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, in this order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("day"), new DateColumnType()),
                    new Column(new String("orders"), new LongColumnType()),
                    new Column(new String("revenue"), new DoubleColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("day"), new DateColumnType()),
                                new InvariantCell(
                                    new Date(
                                        new UShort(31),
