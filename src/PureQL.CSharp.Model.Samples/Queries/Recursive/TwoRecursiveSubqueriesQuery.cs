namespace PureQL.CSharp.Model.Samples.Queries.Recursive;

/// <summary>
/// Selects the employee hierarchy around Hank, the employee 000002be, in two recursive
/// subqueries and combines them with a union all. The subquery team starts from the
/// employee whose employee_id is that of Hank, selecting employee_id as id and
/// employee_manager_id as referrer_id, and, level by level, adds every employee of
/// schema_with_foreign_keys.employees whose manager is already in team (maxDepth 50). The
/// subquery upline reads team as an earlier subquery: it starts from the row of team
/// whose id is that of Hank, with level 0, and walks up by joining the employee whose id
/// is the referrer_id of the row before, unless that employee is in team (in over the
/// column id of team), with level - 1 (maxDepth 3). The main query returns the id of
/// every row of team with the side "below", followed by the id of every row of upline
/// whose level is below 0 with the side "above".
/// </summary>
public sealed record TwoRecursiveSubqueriesQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainCombinedQueryUnionAll(
            subqueries:
            [
                new SubqueryRecursive(
                    "team",
                    new Recursion(
                        new PlainQueryWithoutPaginationWithoutOrderBy(
                            from: new FromEntity(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new EmployeesTable().Name,
                                    ]
                                ).TextValue
                            ),
                            where: new EqualUuidRow(
                                new FieldUuid(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new EmployeesTable().Name,
                                        ]
                                    ).TextValue,
                                    new EmployeeIdColumn().Name.TextValue
                                ),
                                new LiteralUuid(new System.Guid(702, 0, 0, new byte[8]))
                            ),
                            select:
                            [
                                new SelectItemProjection(
                                    "id",
                                    new FieldUuid(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeIdColumn().Name.TextValue
                                    )
                                ),
                                new SelectItemProjection(
                                    "referrer_id",
                                    new FieldUuidNullable(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeManagerIdColumn().Name.TextValue
                                    )
                                ),
                            ]
                        ),
                        new PlainNextQuery(
                            from: new FromEntity(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new EmployeesTable().Name,
                                    ]
                                ).TextValue
                            ),
                            joins:
                            [
                                new JoinSubquery(
                                    JoinKind.Inner,
                                    "team",
                                    new EqualUuidRow(
                                        new FieldUuidNullable(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new EmployeesTable().Name,
                                                ]
                                            ).TextValue,
                                            new EmployeeManagerIdColumn().Name.TextValue
                                        ),
                                        new FieldUuid("team", "id")
                                    )
                                ),
                            ],
                            select:
                            [
                                new SelectItemRow(
                                    "id",
                                    new FieldUuid(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeIdColumn().Name.TextValue
                                    )
                                ),
                                new SelectItemRow(
                                    "referrer_id",
                                    new FieldUuidNullable(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeManagerIdColumn().Name.TextValue
                                    )
                                ),
                            ]
                        ),
                        50
                    )
                ),
                new SubqueryRecursive(
                    "upline",
                    new Recursion(
                        new PlainQueryWithoutPaginationWithoutOrderBy(
                            from: new FromSubquery("team"),
                            where: new EqualUuidRow(
                                new FieldUuid("team", "id"),
                                new LiteralUuid(new System.Guid(702, 0, 0, new byte[8]))
                            ),
                            select:
                            [
                                new SelectItemProjection(
                                    "id",
                                    new FieldUuid("team", "id")
                                ),
                                new SelectItemProjection(
                                    "referrer_id",
                                    new FieldUuidNullable("team", "referrer_id")
                                ),
                                new SelectItemProjection("level", new LiteralInteger(0)),
                            ]
                        ),
                        new PlainNextQuery(
                            from: new FromSubquery("upline"),
                            joins:
                            [
                                new JoinEntity(
                                    JoinKind.Inner,
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new EmployeesTable().Name,
                                        ]
                                    ).TextValue,
                                    new EqualUuidRow(
                                        new FieldUuid(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new EmployeesTable().Name,
                                                ]
                                            ).TextValue,
                                            new EmployeeIdColumn().Name.TextValue
                                        ),
                                        new FieldUuidNullable("upline", "referrer_id")
                                    )
                                ),
                            ],
                            where: new NotRow(
                                new InUuidRow(
                                    new FieldUuid(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeIdColumn().Name.TextValue
                                    ),
                                    new ListSubqueryColumnUuid("team", "id")
                                )
                            ),
                            select:
                            [
                                new SelectItemRow(
                                    "id",
                                    new FieldUuid(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeIdColumn().Name.TextValue
                                    )
                                ),
                                new SelectItemRow(
                                    "referrer_id",
                                    new FieldUuidNullable(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new EmployeesTable().Name,
                                            ]
                                        ).TextValue,
                                        new EmployeeManagerIdColumn().Name.TextValue
                                    )
                                ),
                                new SelectItemRow(
                                    "level",
                                    new SubtractIntegerRow([
                                        new FieldInteger("upline", "level"),
                                        new LiteralInteger(1),
                                    ])
                                ),
                            ]
                        ),
                        3
                    )
                ),
            ],
            unionAll:
            [
                new PlainQueryWithoutPaginationWithoutOrderBy(
                    from: new FromSubquery("team"),
                    select:
                    [
                        new SelectItemProjection("id", new FieldUuid("team", "id")),
                        new SelectItemProjection("side", new LiteralString("below")),
                    ]
                ),
                new PlainQueryWithoutPaginationWithoutOrderBy(
                    from: new FromSubquery("upline"),
                    where: new LessThanDecimalRow(
                        new FieldInteger("upline", "level"),
                        new LiteralInteger(0)
                    ),
                    select:
                    [
                        new SelectItemProjection("id", new FieldUuid("upline", "id")),
                        new SelectItemProjection("side", new LiteralString("above")),
                    ]
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over <see
    /// cref="SchemaDataSetWithForeignKeys"/> and <see cref="AuditSchemaDataSet"/>, in no
    /// particular order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("id"), new UuidColumnType()),
                    new Column(new String("side"), new StringColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("id"), new UuidColumnType()),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002be-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("side"), new StringColumnType()),
                                new InvariantCell(new String("below"))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("id"), new UuidColumnType()),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002c0-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("side"), new StringColumnType()),
                                new InvariantCell(new String("below"))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("id"), new UuidColumnType()),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002bd-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("side"), new StringColumnType()),
                                new InvariantCell(new String("above"))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
