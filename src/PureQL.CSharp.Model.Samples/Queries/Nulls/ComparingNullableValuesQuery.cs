                            new FieldDatetimeNullable(
                                "latest_logins",
                                "last_audit_login"
                            ),
                            new FieldDatetimeNullable("first_orders", "first_order_at")
                        ),
                    ])
                ),
                new SelectItemProjection(
                    "neither_happened",
                    new AndProjection([
                        new EqualDatetimeProjection(
                            new FieldDatetimeNullable(
                                "latest_logins",
                                "last_audit_login"
                            ),
                            new LiteralDatetimeNullable()
                        ),
                        new EqualDatetimeProjection(
                            new FieldDatetimeNullable("first_orders", "first_order_at"),
                            new LiteralDatetimeNullable()
                        ),
                    ])
                ),
                new SelectItemProjection(
                    "logged_in_by_deadline",
                    new LessThanOrEqualDatetimeProjection(
                        new FieldDatetimeNullable("latest_logins", "last_audit_login"),
                        new LiteralDatetimeNullable()
                    )
                ),
                new SelectItemProjection(
                    "logged_in_exactly_at_deadline",
                    new AndProjection([
                        new LessThanOrEqualDatetimeProjection(
                            new FieldDatetimeNullable(
                                "latest_logins",
                                "last_audit_login"
                            ),
                            new LiteralDatetimeNullable()
                        ),
