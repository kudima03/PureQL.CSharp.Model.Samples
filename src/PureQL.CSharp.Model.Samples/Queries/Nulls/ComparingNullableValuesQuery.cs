/// <summary>
/// Selects from schema_with_foreign_keys.users left joined on user_id to two grouped
/// subqueries, latest_logins (the max login_at per login_user_id of audit.logins) and
/// first_orders (the min placed_at per order_user_id of schema_with_foreign_keys.orders):
/// user_id, whether last_audit_login is greater than or equal to first_order_at, greater
/// than it, greater than or equal to it, whether both are null, and whether
/// last_audit_login is at most, and both at most and at least, a deadline that is a typed
/// null datetime, ordered by user_id.
/// </summary>
public sealed record ComparingNullableValuesQuery
