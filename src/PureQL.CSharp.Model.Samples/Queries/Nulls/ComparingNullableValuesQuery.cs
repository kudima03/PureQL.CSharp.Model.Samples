                            new FieldDatetimeNullable(
                                "latest_logins",
                                "last_audit_login"
                            ),
                            new LiteralDatetimeNullable()
                        ),
                    ])
                ),
            ],
            orderBy:
            [
                new OrderItemProjectionExpression(
                    new FieldUuid(
