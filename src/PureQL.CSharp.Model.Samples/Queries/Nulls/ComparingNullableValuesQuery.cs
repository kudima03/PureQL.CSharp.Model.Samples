                        new FieldUuid("latest_logins", "user_id")
                    )
                ),
                new JoinSubquery(
                    JoinKind.Left,
                    "first_orders",
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new UserIdColumn().Name.TextValue
