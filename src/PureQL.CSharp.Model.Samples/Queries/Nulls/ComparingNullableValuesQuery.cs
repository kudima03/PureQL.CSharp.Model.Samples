            [
                new SelectItemProjection(
                    "user_id",
                    new FieldUuid(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new UsersTable().Name,
                            ]
                        ).TextValue,
                        new UserIdColumn().Name.TextValue
                    )
                ),
                new SelectItemProjection(
                    "logged_in_since_first_order",
                    new GreaterThanOrEqualDatetimeProjection(
                        new FieldDatetimeNullable("latest_logins", "last_audit_login"),
                        new FieldDatetimeNullable("first_orders", "first_order_at")
                    )
                ),
                new SelectItemProjection(
                    "logged_in_after_first_order",
                    new GreaterThanDatetimeProjection(
                        new FieldDatetimeNullable("latest_logins", "last_audit_login"),
                        new FieldDatetimeNullable("first_orders", "first_order_at")
                    )
                ),
                new SelectItemProjection(
                    "after_or_at_the_same_time",
                    new OrProjection([
                        new GreaterThanDatetimeProjection(
                            new FieldDatetimeNullable(
                                "latest_logins",
                                "last_audit_login"
                            ),
                            new FieldDatetimeNullable("first_orders", "first_order_at")
                        ),
