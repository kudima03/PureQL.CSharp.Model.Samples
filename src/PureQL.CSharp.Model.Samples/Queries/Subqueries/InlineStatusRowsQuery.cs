/// <summary>
/// Selects order_id, the label of its status, or order_status where the label is null,
/// and the rank of its status from schema_with_foreign_keys.orders left joined on
/// order_status to a subquery statuses of inline rows (pending ranked 1 and labelled
/// "Awaiting shipment", shipped ranked 2 and labelled "Shipped", cancelled ranked 3 with
/// a null label), ordered by rank, then by order_id.
/// </summary>
public sealed record InlineStatusRowsQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            subqueries:
            [
                new SubqueryRows(
                    "statuses",
                    [
                        [
                            new RowItem("status", new LiteralString("pending")),
                            new RowItem("rank", new LiteralInteger(1)),
                            new RowItem("label", new LiteralString("Awaiting shipment")),
                        ],
                        [
                            new RowItem("status", new LiteralString("shipped")),
                            new RowItem("rank", new LiteralInteger(2)),
                            new RowItem("label", new LiteralString("Shipped")),
                        ],
                        [
                            new RowItem("status", new LiteralString("cancelled")),
                            new RowItem("rank", new LiteralInteger(3)),
                            new RowItem("label", new LiteralStringNullable()),
                        ],
                    ]
                ),
            ],
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new OrdersTable().Name]
                ).TextValue
            ),
            joins:
            [
                new JoinSubquery(
                    JoinKind.Left,
                    "statuses",
                    new EqualStringRow(
                        new FieldString(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderStatusColumn().Name.TextValue
                        ),
                        new FieldString("statuses", "status")
                    )
                ),
            ],
            select:
            [
                new SelectItemProjection(
                    "order_id",
                    new FieldUuid(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new OrdersTable().Name,
                            ]
                        ).TextValue,
                        new OrderIdColumn().Name.TextValue
                    )
                ),
                new SelectItemProjection(
                    "status",
                    new CoalesceStringProjection([
                        new FieldStringNullable("statuses", "label"),
                        new FieldString(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderStatusColumn().Name.TextValue
                        ),
                    ])
                ),
                new SelectItemProjection(
                    "rank",
                    new FieldIntegerNullable("statuses", "rank")
                ),
            ],
            orderBy:
            [
                new OrderItemProjectionExpression(
                    new FieldIntegerNullable("statuses", "rank")
                ),
                new OrderItemProjectionExpression(
                    new FieldUuid(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new OrdersTable().Name,
                            ]
                        ).TextValue,
                        new OrderIdColumn().Name.TextValue
                    )
                ),
            ]
        );

