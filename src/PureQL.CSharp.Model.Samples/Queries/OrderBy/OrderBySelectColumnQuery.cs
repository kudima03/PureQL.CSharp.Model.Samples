/// <summary>
/// Selects from schema_with_foreign_keys.orders grouped by order_user_id: the key, the
/// sum of order_total, the sum of order_total where order_status equals shipped, the
/// count, and the sum divided by the count, ordered by the select columns shipped_revenue
/// descending, average_order descending and order_user_id, each named by its alias, with
/// a take of 10.
/// </summary>
public sealed record OrderBySelectColumnQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainGroupedQueryWithPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new OrdersTable().Name]
                ).TextValue
            ),
            groupBy:
            [
                new GroupKey(
                    "order_user_id",
                    new FieldUuid(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new OrdersTable().Name,
                            ]
                        ).TextValue,
                        new OrderUserIdColumn().Name.TextValue
                    )
                ),
            ],
            select:
            [
                new SelectItemGroup("order_user_id", new KeyUuid("order_user_id")),
                new SelectItemGroup(
                    "revenue",
                    new SumDecimalGroup(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderTotalColumn().Name.TextValue
                        )
                    )
                ),
                new SelectItemGroup(
                    "shipped_revenue",
                    new SumDecimalGroup(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderTotalColumn().Name.TextValue
                        ),
                        new EqualStringRow(
                            new FieldString(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new OrderStatusColumn().Name.TextValue
                            ),
                            new LiteralString("shipped")
                        )
                    )
                ),
                new SelectItemGroup("orders", new CountGroup()),
                new SelectItemGroup(
                    "average_order",
                    new DivideDecimalGroup([
                        new SumDecimalGroup(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new OrderTotalColumn().Name.TextValue
                            )
                        ),
                        new CountGroup(),
                    ])
                ),
            ],
            orderBy:
            [
                new OrderItemGroupColumn("shipped_revenue", SortDirection.Desc),
                new OrderItemGroupColumn("average_order", SortDirection.Desc),
                new OrderItemGroupColumn("order_user_id"),
            ],
            pagination: new ModelPagination(take: 10)
        );

