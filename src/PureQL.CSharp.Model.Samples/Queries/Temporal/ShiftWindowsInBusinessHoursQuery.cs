namespace PureQL.CSharp.Model.Samples.Queries.Temporal;

/// <summary>
/// Selects employee_id, employee_shift_start as window_start, employee_shift_start plus 2
/// times 3600 seconds as window_end and the seconds from employee_shift_start to 18:00:00
/// divided by the integer 3600 as hours_until_closing from
/// schema_with_foreign_keys.employees, where employee_shift_start is greater than or
/// equal to 09:00:00 and less than 18:00:00, ordered by employee_shift_start.
/// </summary>
public sealed record ShiftWindowsInBusinessHoursQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [
                        new RelationalSchemaWithForeignKeys().Name,
                        new EmployeesTable().Name,
                    ]
                ).TextValue
            ),
            where: new AndRow([
                new GreaterThanOrEqualTimeRow(
                    new FieldTime(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new EmployeesTable().Name,
                            ]
                        ).TextValue,
                        new EmployeeShiftStartColumn().Name.TextValue
                    ),
                    new LiteralTime(new TimeOnly(9, 0, 0))
                ),
                new LessThanTimeRow(
                    new FieldTime(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new EmployeesTable().Name,
                            ]
                        ).TextValue,
                        new EmployeeShiftStartColumn().Name.TextValue
                    ),
                    new LiteralTime(new TimeOnly(18, 0, 0))
                ),
            ]),
            select:
            [
                new SelectItemProjection(
                    "employee_id",
                    new FieldUuid(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new EmployeesTable().Name,
                            ]
                        ).TextValue,
                        new EmployeeIdColumn().Name.TextValue
                    )
                ),
                new SelectItemProjection(
                    "window_start",
                    new FieldTime(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new EmployeesTable().Name,
                            ]
                        ).TextValue,
                        new EmployeeShiftStartColumn().Name.TextValue
                    )
                ),
                new SelectItemProjection(
                    "window_end",
                    new TimeAddSecondsTimeProjection(
                        new FieldTime(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new EmployeesTable().Name,
                                ]
                            ).TextValue,
                            new EmployeeShiftStartColumn().Name.TextValue
                        ),
                        new MultiplyIntegerProjection([
                            new LiteralInteger(2),
                            new LiteralInteger(3600),
                        ])
                    )
                ),
                new SelectItemProjection(
                    "hours_until_closing",
                    new DivideDecimalProjection([
                        new TimeDiffSecondsDecimalProjection(
                            new LiteralTime(new TimeOnly(18, 0, 0)),
                            new FieldTime(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new EmployeesTable().Name,
                                    ]
                                ).TextValue,
                                new EmployeeShiftStartColumn().Name.TextValue
                            )
                        ),
                        new LiteralInteger(3600),
                    ])
                ),
            ],
            orderBy:
            [
                new OrderItemProjectionExpression(
                    new FieldTime(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new EmployeesTable().Name,
                            ]
                        ).TextValue,
                        new EmployeeShiftStartColumn().Name.TextValue
                    )
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, in this order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new EmployeeIdColumn(),
                    new Column(new String("window_start"), new TimeColumnType()),
                    new Column(new String("window_end"), new TimeColumnType()),
                    new Column(new String("hours_until_closing"), new DoubleColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new EmployeeIdColumn(),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002bd-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_start"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(new UShort(9), new UShort(0), new UShort(0))
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_end"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(new UShort(11), new UShort(0), new UShort(0))
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hours_until_closing"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(9.0))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new EmployeeIdColumn(),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002be-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_start"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(new UShort(10), new UShort(0), new UShort(0))
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_end"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(new UShort(12), new UShort(0), new UShort(0))
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hours_until_closing"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(8.0))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new EmployeeIdColumn(),
                                new InvariantCell(
                                    new Guid(
                                        new System.Guid(
                                            "000002bf-0000-0000-0000-000000000000"
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_start"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(
                                        new UShort(11),
                                        new UShort(30),
                                        new UShort(0)
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("window_end"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(
                                        new UShort(13),
                                        new UShort(30),
                                        new UShort(0)
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hours_until_closing"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(6.5))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
