namespace PureQL.CSharp.Model.Samples.Queries.Temporal;

/// <summary>
/// Selects user_name and trial_start plus 14 days as trial_ends_on from
/// schema_with_foreign_keys.users left joined with the subquery trials of inline rows (a
/// trial_start date for the users 1, 2, 3, 4 and 6) on user_id equal to its user_id,
/// where that end of the trial is greater than or equal to the date 2024-06-10 and the
/// days from that date to the end of the trial are less than or equal to the integer 3,
/// ordered by the end of the trial, then by user_name.
/// </summary>
public sealed record TrialsEndingWithinThreeDaysQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            subqueries:
            [
                new SubqueryRows(
                    "trials",
                    [
                        [
                            new RowItem(
                                "user_id",
                                new LiteralUuid(new Guid(1, 0, 0, new byte[8]))
                            ),
                            new RowItem(
                                "trial_start",
                                new LiteralDate(new DateOnly(2024, 5, 28))
                            ),
                        ],
                        [
                            new RowItem(
                                "user_id",
                                new LiteralUuid(new Guid(2, 0, 0, new byte[8]))
                            ),
                            new RowItem(
                                "trial_start",
                                new LiteralDate(new DateOnly(2024, 5, 25))
                            ),
                        ],
                        [
                            new RowItem(
                                "user_id",
                                new LiteralUuid(new Guid(3, 0, 0, new byte[8]))
                            ),
                            new RowItem(
                                "trial_start",
                                new LiteralDate(new DateOnly(2024, 6, 1))
                            ),
                        ],
                        [
                            new RowItem(
                                "user_id",
                                new LiteralUuid(new Guid(4, 0, 0, new byte[8]))
                            ),
                            new RowItem(
                                "trial_start",
                                new LiteralDate(new DateOnly(2024, 5, 27))
                            ),
                        ],
                        [
                            new RowItem(
                                "user_id",
                                new LiteralUuid(new Guid(6, 0, 0, new byte[8]))
                            ),
                            new RowItem(
                                "trial_start",
                                new LiteralDate(new DateOnly(2024, 5, 30))
                            ),
                        ],
                    ]
                ),
            ],
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new UsersTable().Name]
                ).TextValue
            ),
            joins:
            [
                new JoinSubquery(
                    JoinKind.Left,
                    "trials",
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new UserIdColumn().Name.TextValue
                        ),
                        new FieldUuid("trials", "user_id")
                    )
                ),
            ],
            where: new AndRow([
                new GreaterThanOrEqualDateRow(
                    new DateAddDaysDateNullableRow(
                        new FieldDateNullable("trials", "trial_start"),
                        new LiteralInteger(14)
                    ),
                    new LiteralDate(new DateOnly(2024, 6, 10))
                ),
                new LessThanOrEqualDecimalRow(
                    new DateDiffDaysIntegerNullableRow(
                        new DateAddDaysDateNullableRow(
                            new FieldDateNullable("trials", "trial_start"),
                            new LiteralInteger(14)
                        ),
                        new LiteralDate(new DateOnly(2024, 6, 10))
                    ),
                    new LiteralInteger(3)
                ),
            ]),
            select:
            [
                new SelectItemProjection(
                    "user_name",
                    new FieldString(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new UsersTable().Name,
                            ]
                        ).TextValue,
                        new UserNameColumn().Name.TextValue
                    )
                ),
                new SelectItemProjection(
                    "trial_ends_on",
                    new DateAddDaysDateNullableProjection(
                        new FieldDateNullable("trials", "trial_start"),
                        new LiteralInteger(14)
                    )
                ),
            ],
            orderBy:
            [
                new OrderItemProjectionExpression(
                    new DateAddDaysDateNullableProjection(
                        new FieldDateNullable("trials", "trial_start"),
                        new LiteralInteger(14)
                    )
                ),
                new OrderItemProjectionExpression(
                    new FieldString(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new UsersTable().Name,
                            ]
                        ).TextValue,
                        new UserNameColumn().Name.TextValue
                    )
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, in this order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new UserNameColumn(),
                    new Column(new String("trial_ends_on"), new DateColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new UserNameColumn(),
                                new InvariantCell(new String("Dan"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("trial_ends_on"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(10),
                                        new UShort(6),
                                        new UShort(2024)
                                    )
                                )
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new UserNameColumn(),
                                new InvariantCell(new String("Ann"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("trial_ends_on"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(11),
                                        new UShort(6),
                                        new UShort(2024)
                                    )
                                )
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new UserNameColumn(),
                                new InvariantCell(new String("Fay"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("trial_ends_on"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(13),
                                        new UShort(6),
                                        new UShort(2024)
                                    )
                                )
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
