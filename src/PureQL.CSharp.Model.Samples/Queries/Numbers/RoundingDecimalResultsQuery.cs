/// <summary>
/// Selects, from schema_with_foreign_keys.order_items inner joined with
/// schema_with_foreign_keys.products on item_product_id equal to product_id, whole
/// numbers from decimal results, with the quantity being item_qty rounded to an integer:
/// the floor of the quantity divided by 3, the ceiling of product_price times the
/// quantity, the rounded quantity to the power 0.5, the truncated square root of the
/// quantity, the rounded coalesce of product_price (null where it equals 9.99) and 0, the
/// floor of an if giving product_price where the quantity is greater than 2 and 0
/// otherwise, the ceiling of that nullable price, the truncated decimal literal 2.5, the
/// rounded average of the quantity over all rows, the floor of the absolute difference of
/// product_price and 9.99, and the rounded text -3.5 read as a decimal.
/// </summary>
public sealed record RoundingDecimalResultsQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [
                        new RelationalSchemaWithForeignKeys().Name,
                        new OrderItemsTable().Name,
                    ]
                ).TextValue
            ),
            joins:
            [
                new JoinEntity(
                    JoinKind.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new ProductsTable().Name,
                        ]
                    ).TextValue,
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrderItemsTable().Name,
                                ]
                            ).TextValue,
                            new ItemProductIdColumn().Name.TextValue
                        ),
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductIdColumn().Name.TextValue
                        )
                    )
                ),
            ],
            select:
            [
                new SelectItemProjection(
                    "of_a_quotient",
                    new FloorIntegerProjection(
                        new DivideDecimalProjection([
                            new RoundWithoutDigitsIntegerProjection(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            ),
                            new LiteralInteger(3),
                        ])
                    )
                ),
                new SelectItemProjection(
                    "of_a_product",
                    new CeilingIntegerProjection(
                        new MultiplyDecimalProjection([
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            new RoundWithoutDigitsIntegerProjection(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            ),
                        ])
                    )
                ),
                new SelectItemProjection(
                    "of_a_power",
                    new RoundWithoutDigitsIntegerProjection(
                        new PowerDecimalProjection(
                            new RoundWithoutDigitsIntegerProjection(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            ),
                            new LiteralDecimal(0.5m)
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_square_root",
                    new TruncateWithoutDigitsIntegerProjection(
                        new SqrtDecimalProjection(
                            new RoundWithoutDigitsIntegerProjection(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            )
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_decimal_coalesce",
                    new RoundWithoutDigitsIntegerProjection(
                        new CoalesceDecimalProjection([
                            new NullIfEqualDecimalNullableProjection(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new ProductsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ProductPriceColumn().Name.TextValue
                                ),
                                new LiteralDecimal(9.99m)
                            ),
                            new LiteralInteger(0),
                        ])
                    )
                ),
                new SelectItemProjection(
                    "of_a_decimal_if",
                    new FloorIntegerProjection(
                        new IfDecimalProjection(
                            then: new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            @else: new LiteralInteger(0),
                            condition: new GreaterThanDecimalProjection(
                                new RoundWithoutDigitsIntegerProjection(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrderItemsTable().Name,
                                            ]
                                        ).TextValue,
                                        new ItemQtyColumn().Name.TextValue
                                    )
                                ),
                                new LiteralInteger(2)
                            )
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_nullable_decimal",
                    new CeilingIntegerNullableProjection(
                        new NullIfEqualDecimalNullableProjection(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            new LiteralDecimal(9.99m)
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_decimal_literal",
                    new TruncateWithoutDigitsIntegerProjection(new LiteralDecimal(2.5m))
                ),
                new SelectItemProjection(
                    "of_an_average_over_all",
                    new RoundWithoutDigitsIntegerProjection(
                        new AverageDecimalProjection(
                            new RoundWithoutDigitsIntegerRow(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            )
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_decimal_abs",
                    new FloorIntegerProjection(
                        new AbsDecimalProjection(
                            new SubtractDecimalProjection([
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new ProductsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ProductPriceColumn().Name.TextValue
                                ),
                                new LiteralDecimal(9.99m),
                            ])
                        )
                    )
                ),
                new SelectItemProjection(
                    "of_a_string_read_as_decimal",
                    new RoundWithoutDigitsIntegerProjection(
                        new AsDecimalStringDecimalProjection(new LiteralString("-3.5"))
                    )
                ),
            ]
        );

