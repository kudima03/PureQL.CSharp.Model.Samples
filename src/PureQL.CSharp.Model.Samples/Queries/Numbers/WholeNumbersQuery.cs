/// <summary>
/// Selects from schema_with_foreign_keys.order_items inner joined to
/// schema_with_foreign_keys.products on item_product_id: item_id, item_qty rounded to the
/// integer units, product_price rounded and floored, the product of product_price and
/// units rounded up with ceiling, units divided by 2 and truncated, units rounded to tens
/// with digits -1, which keeps an integer, and units integer-divided by 2, ordered by
/// item_id.
/// </summary>
public sealed record WholeNumbersQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [
                        new RelationalSchemaWithForeignKeys().Name,
                        new OrderItemsTable().Name,
                    ]
                ).TextValue
