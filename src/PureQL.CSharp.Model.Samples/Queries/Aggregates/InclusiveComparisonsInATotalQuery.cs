/// <summary>
/// Selects, over all of schema_with_foreign_keys.orders, the number of orders whose
/// shipped date is at least a nullable bound, after it, and equal to it, whether every
/// shipped date is at most the bound, whether the latest shipped date is at least the latest
/// bound, and whether any nullable coupon is at least a nullable tenant. A shipped date is
/// placed_on for the shipped orders and null for the others, the bound is 2024-06-03 for the
/// orders with an order_total over 100 and null for the others, the coupon is the
/// order_user_id of the shipped orders and the tenant the order_tenant_id of the orders over
/// 100.
/// </summary>
public sealed record InclusiveComparisonsInATotalQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainTotalQuery(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new OrdersTable().Name]
                ).TextValue
            ),
            aggregate:
            [
                new SelectItemTotal(
                    "at_or_after_from",
                    new CountTotal(
                        predicate: new GreaterThanOrEqualDateRow(
                            new IfDateNullableRow(
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                ),
                                new LiteralDateNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            ),
                            new IfDateNullableRow(
                                new LiteralDate(new DateOnly(2024, 6, 3)),
                                new LiteralDateNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "after_from",
                    new CountTotal(
                        predicate: new GreaterThanDateRow(
                            new IfDateNullableRow(
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                ),
                                new LiteralDateNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            ),
                            new IfDateNullableRow(
                                new LiteralDate(new DateOnly(2024, 6, 3)),
                                new LiteralDateNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "equal_to_from",
                    new CountTotal(
                        predicate: new EqualDateRow(
                            new IfDateNullableRow(
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                ),
                                new LiteralDateNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            ),
                            new IfDateNullableRow(
                                new LiteralDate(new DateOnly(2024, 6, 3)),
                                new LiteralDateNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "all_at_or_before_from",
                    new AllTotal(
                        new LessThanOrEqualDateRow(
                            new IfDateNullableRow(
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                ),
                                new LiteralDateNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            ),
                            new IfDateNullableRow(
                                new LiteralDate(new DateOnly(2024, 6, 3)),
                                new LiteralDateNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "latest_is_at_or_after_latest_from",
                    new GreaterThanOrEqualDateTotal(
                        new MaxDateNullableTotal(
                            new IfDateNullableRow(
                                new FieldDate(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedOnColumn().Name.TextValue
                                ),
                                new LiteralDateNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            )
                        ),
                        new MaxDateNullableTotal(
                            new IfDateNullableRow(
                                new LiteralDate(new DateOnly(2024, 6, 3)),
                                new LiteralDateNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "any_coupon_at_or_after_tenant",
                    new AnyTotal(
                        new GreaterThanOrEqualUuidRow(
                            new IfUuidNullableRow(
                                new FieldUuid(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new OrderUserIdColumn().Name.TextValue
                                ),
                                new LiteralUuidNullable(),
                                new EqualStringRow(
                                    new FieldString(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderStatusColumn().Name.TextValue
                                    ),
                                    new LiteralString("shipped")
                                )
                            ),
                            new IfUuidNullableRow(
                                new FieldUuid(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new OrderTenantIdColumn().Name.TextValue
                                ),
                                new LiteralUuidNullable(),
                                new GreaterThanDecimalRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrdersTable().Name,
                                            ]
                                        ).TextValue,
                                        new OrderTotalColumn().Name.TextValue
                                    ),
                                    new LiteralDecimal(100m)
                                )
                            )
                        )
                    )
                ),
            ]
        );

    /// <summary>
    /// The single row of the total query computed over the fixture rows. The first count is the
    /// sum of the next two, null bounds included.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("at_or_after_from"), new LongColumnType()),
                    new Column(new String("after_from"), new LongColumnType()),
                    new Column(new String("equal_to_from"), new LongColumnType()),
                    new Column(new String("all_at_or_before_from"), new BoolColumnType()),
                    new Column(
                        new String("latest_is_at_or_after_latest_from"),
                        new BoolColumnType()
                    ),
                    new Column(
                        new String("any_coupon_at_or_after_tenant"),
                        new BoolColumnType()
                    ),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("at_or_after_from"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(4))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("after_from"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(1))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("equal_to_from"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(3))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("all_at_or_before_from"),
                                    new BoolColumnType()
                                ),
                                new InvariantCell(new False())
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("latest_is_at_or_after_latest_from"),
                                    new BoolColumnType()
                                ),
                                new InvariantCell(new True())
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("any_coupon_at_or_after_tenant"),
                                    new BoolColumnType()
                                ),
                                new InvariantCell(new True())
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
