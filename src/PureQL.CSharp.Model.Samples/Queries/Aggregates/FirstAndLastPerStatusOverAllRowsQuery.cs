                                    new OrderIdColumn().Name.TextValue
                                )
                            ),
                        ]
                    )
                ),
                new SelectItemGroup(
                    "latest_total_of_all",
                    new LastDecimalGroup(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
