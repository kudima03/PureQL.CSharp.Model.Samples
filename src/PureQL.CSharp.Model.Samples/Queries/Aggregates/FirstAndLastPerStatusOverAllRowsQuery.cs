/// <summary>
/// Selects from schema_with_foreign_keys.orders grouped by order_status, keeping the
/// groups whose last order_total in placed_at then order_id order is greater than 100:
/// the key, the first placed_at, whether the first order_id of the group is the first of
/// all the rows (over all), the last order_total of the group and of all the rows, and
/// the first order_id in the order of the days from placed_on to the shipping date
/// (placed_on plus order_total in hundreds, rounded, as days for a shipped order, a typed
/// null otherwise) descending, then 0 for a shipped order and 1 otherwise, then order_id.
/// Ordered by the last placed_at of the group descending, then the key.
/// </summary>
public sealed record FirstAndLastPerStatusOverAllRowsQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainGroupedQueryWithoutPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new OrdersTable().Name]
