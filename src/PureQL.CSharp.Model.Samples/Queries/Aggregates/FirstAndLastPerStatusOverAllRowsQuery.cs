                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new OrderIdColumn().Name.TextValue
                            )
                        ),
                    ]
                ),
                new LiteralDecimal(100m)
            ),
            select:
            [
                new SelectItemGroup("status", new KeyString("status")),
                new SelectItemGroup(
                    "first_ordered_at",
                    new FirstDatetimeGroup(
                        new FieldDatetime(
                            new JoinedString(
