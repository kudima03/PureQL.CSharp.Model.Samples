/// <summary>
/// Selects, as a total query over schema_with_foreign_keys.order_items inner joined to
/// schema_with_foreign_keys.products, schema_with_foreign_keys.orders and
/// schema_with_foreign_keys.users, kept where the floor of item_qty (the quantity as an
/// integer) is above 0: the regressionSlope, regressionIntercept and regressionRSquared
/// of product_price on the quantity, the slope with the predicate that the quantity is
/// above 1, the slope of the quantity on product_price, the slope by hand (the
/// covariancePopulation of the quantity and product_price divided by the
/// variancePopulation of the quantity guarded with nullIfEqual against 0), the square of
/// the correlation of product_price and the quantity, the price predicted for a quantity
/// of 10 (the intercept plus the slope times 10), and the slope of the product of
/// product_price and the nullable user_score on the quantity.
/// </summary>
public sealed record RegressionInATotalQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainTotalQuery(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [
                        new RelationalSchemaWithForeignKeys().Name,
                        new OrderItemsTable().Name,
                    ]
                ).TextValue
            ),
            joins:
            [
                new JoinEntity(
                    JoinKind.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new ProductsTable().Name,
                        ]
                    ).TextValue,
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductIdColumn().Name.TextValue
                        ),
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrderItemsTable().Name,
                                ]
                            ).TextValue,
                            new ItemProductIdColumn().Name.TextValue
                        )
                    )
                ),
                new JoinEntity(
                    JoinKind.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new OrdersTable().Name,
                        ]
                    ).TextValue,
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderIdColumn().Name.TextValue
                        ),
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrderItemsTable().Name,
                                ]
                            ).TextValue,
                            new ItemOrderIdColumn().Name.TextValue
                        )
                    )
                ),
                new JoinEntity(
                    JoinKind.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new UsersTable().Name,
                        ]
                    ).TextValue,
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new UserIdColumn().Name.TextValue
                        ),
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderUserIdColumn().Name.TextValue
                        )
                    )
                ),
            ],
            where: new GreaterThanDecimalRow(
                new FloorIntegerRow(
                    new FieldDecimal(
                        new JoinedString(
                            new DotString(),
                            [
                                new RelationalSchemaWithForeignKeys().Name,
                                new OrderItemsTable().Name,
                            ]
                        ).TextValue,
                        new ItemQtyColumn().Name.TextValue
                    )
                ),
                new LiteralInteger(0)
            ),
            aggregate:
            [
                new SelectItemTotal(
                    "slope",
                    new RegressionSlopeTotal(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductPriceColumn().Name.TextValue
                        ),
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "intercept",
                    new RegressionInterceptTotal(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductPriceColumn().Name.TextValue
                        ),
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "r_squared",
                    new RegressionRSquaredTotal(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductPriceColumn().Name.TextValue
                        ),
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        )
                    )
                ),
                new SelectItemTotal(
                    "slope_of_large_lines",
                    new RegressionSlopeTotal(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductPriceColumn().Name.TextValue
                        ),
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        ),
                        new GreaterThanDecimalRow(
                            new FloorIntegerRow(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            ),
                            new LiteralInteger(1)
                        )
                    )
                ),
                new SelectItemTotal(
                    "the_other_way",
                    new RegressionSlopeTotal(
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        ),
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new ProductsTable().Name,
                                ]
                            ).TextValue,
                            new ProductPriceColumn().Name.TextValue
                        )
                    )
                ),
                new SelectItemTotal(
                    "slope_by_hand",
                    new DivideDecimalNullableTotal([
                        new CovariancePopulationTotal(
                            new FloorIntegerRow(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            ),
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            )
                        ),
                        new NullIfEqualDecimalNullableTotal(
                            new VariancePopulationTotal(
                                new FloorIntegerRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrderItemsTable().Name,
                                            ]
                                        ).TextValue,
                                        new ItemQtyColumn().Name.TextValue
                                    )
                                )
                            ),
                            new LiteralInteger(0)
                        ),
                    ])
                ),
                new SelectItemTotal(
                    "correlation_squared",
                    new PowerDecimalNullableTotal(
                        new CorrelationTotal(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            new FloorIntegerRow(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            )
                        ),
                        new LiteralInteger(2)
                    )
                ),
                new SelectItemTotal(
                    "predicted_price_of_ten",
                    new AddDecimalNullableTotal([
                        new RegressionInterceptTotal(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            new FloorIntegerRow(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrderItemsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ItemQtyColumn().Name.TextValue
                                )
                            )
                        ),
                        new MultiplyDecimalNullableTotal([
                            new RegressionSlopeTotal(
                                new FieldDecimal(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new ProductsTable().Name,
                                        ]
                                    ).TextValue,
                                    new ProductPriceColumn().Name.TextValue
                                ),
                                new FloorIntegerRow(
                                    new FieldDecimal(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithForeignKeys().Name,
                                                new OrderItemsTable().Name,
                                            ]
                                        ).TextValue,
                                        new ItemQtyColumn().Name.TextValue
                                    )
                                )
                            ),
                            new LiteralInteger(10),
                        ]),
                    ])
                ),
                new SelectItemTotal(
                    "with_a_nullable_operand",
                    new RegressionSlopeTotal(
                        new MultiplyDecimalNullableRow([
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new ProductsTable().Name,
                                    ]
                                ).TextValue,
                                new ProductPriceColumn().Name.TextValue
                            ),
                            new FieldDecimalNullable(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new UsersTable().Name,
                                    ]
                                ).TextValue,
                                new UserScoreColumn().Name.TextValue
                            ),
                        ]),
                        new FloorIntegerRow(
                            new FieldDecimal(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrderItemsTable().Name,
                                    ]
                                ).TextValue,
                                new ItemQtyColumn().Name.TextValue
                            )
                        )
                    )
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, as one row, computed from exact decimal
    /// arithmetic in Python (the correlation at 120 places) and rounded as the
    /// specification rounds a decimal.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("slope"), new DoubleColumnType()),
                    new Column(new String("intercept"), new DoubleColumnType()),
                    new Column(new String("r_squared"), new DoubleColumnType()),
                    new Column(
                        new String("slope_of_large_lines"),
                        new DoubleColumnType()
                    ),
                    new Column(new String("the_other_way"), new DoubleColumnType()),
                    new Column(new String("slope_by_hand"), new DoubleColumnType()),
                    new Column(new String("correlation_squared"), new DoubleColumnType()),
                    new Column(
                        new String("predicted_price_of_ten"),
                        new DoubleColumnType()
                    ),
                    new Column(
                        new String("with_a_nullable_operand"),
                        new DoubleColumnType()
                    ),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("slope"), new DoubleColumnType()),
                                new InvariantCell(new Double(-3.411714285714286))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("intercept"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(20.499714285714287))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("r_squared"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(0.8144267692797411))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("slope_of_large_lines"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(-1.9607142857142856))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("the_other_way"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(-0.23871482224931695))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("slope_by_hand"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(-3.411714285714286))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("correlation_squared"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(0.8144267692797411))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("predicted_price_of_ten"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(-13.61742857142857))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("with_a_nullable_operand"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(-150))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
