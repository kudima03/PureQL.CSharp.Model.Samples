/// <summary>
/// Totals the schema_with_foreign_keys.orders joined to schema_with_foreign_keys.users on
/// order_user_id that were placed at or after 2024-09-04T00:00:00Z minus 3 months: the
/// latest placed_on plus 30 days, the earliest shift_start plus 7200 seconds and the
/// earliest placed_at plus 12 months, all nullable, 2024-07-06 plus as many days as
/// orders, and the average of placed_on plus 30 days.
/// </summary>
public sealed record AddedAmountsInATotalQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainTotalQuery(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new OrdersTable().Name]
                ).TextValue
            ),
            joins:
            [
                new JoinEntity(
                    JoinKind.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new UsersTable().Name,
                        ]
                    ).TextValue,
                    new EqualUuidRow(
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue,
                            new OrderUserIdColumn().Name.TextValue
                        ),
                        new FieldUuid(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new UserIdColumn().Name.TextValue
                        )
                    )
                ),
            ],
            where: new GreaterThanOrEqualDatetimeRow(
                new FieldDatetime(
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new OrdersTable().Name,
                        ]
                    ).TextValue,
                    new PlacedAtColumn().Name.TextValue
                ),
                new DatetimeAddMonthsDatetimeRow(
                    new LiteralDatetime(
                        new DateTimeOffset(2024, 9, 4, 0, 0, 0, TimeSpan.Zero)
                    ),
                    new LiteralInteger(-3)
                )
            ),
            aggregate:
            [
                new SelectItemTotal(
                    "latest_due",
                    new DateAddDaysDateNullableTotal(
                        new MaxDateNullableTotal(
                            new FieldDate(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new PlacedOnColumn().Name.TextValue
                            )
                        ),
                        new LiteralInteger(30)
                    )
                ),
                new SelectItemTotal(
                    "earliest_window_end",
                    new TimeAddSecondsTimeNullableTotal(
                        new MinTimeNullableTotal(
                            new FieldTime(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new UsersTable().Name,
                                    ]
                                ).TextValue,
                                new ShiftStartColumn().Name.TextValue
                            )
                        ),
                        new LiteralInteger(7200)
                    )
                ),
                new SelectItemTotal(
                    "a_year_after_the_first",
                    new DatetimeAddMonthsDatetimeNullableTotal(
                        new MinDatetimeNullableTotal(
                            new FieldDatetime(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new PlacedAtColumn().Name.TextValue
                            )
                        ),
                        new LiteralInteger(12)
                    )
                ),
                new SelectItemTotal(
                    "shifted_by_the_count",
                    new DateAddDaysDateTotal(
                        new LiteralDate(new DateOnly(2024, 7, 6)),
                        new CountTotal()
                    )
                ),
                new SelectItemTotal(
                    "average_due",
                    new AverageDateNullableTotal(
                        new DateAddDaysDateRow(
                            new FieldDate(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new PlacedOnColumn().Name.TextValue
                            ),
                            new LiteralInteger(30)
                        )
                    )
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and <see cref="AuditSchemaDataSet"/>,
    /// in this order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("latest_due"), new DateColumnType()),
                    new Column(new String("earliest_window_end"), new TimeColumnType()),
                    new Column(
                        new String("a_year_after_the_first"),
                        new DateTimeColumnType()
                    ),
                    new Column(new String("shifted_by_the_count"), new DateColumnType()),
                    new Column(new String("average_due"), new DateColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("latest_due"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(6),
                                        new UShort(7),
                                        new UShort(2024)
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("earliest_window_end"),
                                    new TimeColumnType()
                                ),
                                new InvariantCell(
                                    new Time(new UShort(11), new UShort(0), new UShort(0))
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("a_year_after_the_first"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(4),
                                            new UShort(6),
                                            new UShort(2025)
                                        ),
                                        new Time(
                                            new UShort(13),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("shifted_by_the_count"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(9),
                                        new UShort(7),
                                        new UShort(2024)
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("average_due"),
                                    new DateColumnType()
                                ),
                                new InvariantCell(
                                    new Date(
                                        new UShort(5),
                                        new UShort(7),
                                        new UShort(2024)
                                    )
                                )
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
