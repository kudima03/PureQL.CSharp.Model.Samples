/// each user of schema_with_foreign_keys.users the zone America/New_York for tenant #901
/// and Asia/Tokyo otherwise, on the same user and placed_at not before the start of the
/// local month of created_at (last_login of an active user, one month later for an
/// inactive one) in that zone, the orders placed from the start of the local day of
/// 2024-06-02T12:00:00Z up to the start of the local hour of 2024-06-06T20:30:00Z:
