/// the one to the other, the count of orders of the user in the same local week (a
/// window), the earliest start of a local quarter of the rows, and the sum of order_total
/// of the user over the 518400 seconds before the local day (a range window ordered by
/// the start of the local day), ordered by the start of the local day descending and the
