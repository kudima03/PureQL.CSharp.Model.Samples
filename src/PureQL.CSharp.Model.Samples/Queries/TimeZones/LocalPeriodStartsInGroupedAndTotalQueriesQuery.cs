/// <summary>
/// Selects the status and the start of the local hour of the keys of a subquery by_hour,
/// joined on true to a subquery totals, with the count of orders in the quarter. by_hour
/// groups schema_with_foreign_keys.orders by placed_at and order_status, keeps the groups
/// whose key is not before the start of the local month of 2024-07-01T09:00:00Z in
/// Pacific/Pago_Pago, and selects the status, the start of the local hour of the key, the
/// start of the local week in Europe/Moscow of the latest placed_at, the number of
/// different local days and the latest start of a local month. totals is a total query
/// over the orders placed from the start of the local quarter of the same instant: their
/// count, the number of different local days, the start of the local month of the first
/// order (nullable) and the most frequent start of a local day (nullable).
/// </summary>
public sealed record LocalPeriodStartsInGroupedAndTotalQueriesQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainPlainQueryWithoutPagination(
            subqueries:
            [
                new SubqueryQuery(
                    "by_hour",
                    new GroupedQueryWithoutPaginationWithoutOrderBy(
                        from: new FromEntity(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue
                        ),
                        groupBy:
                        [
                            new GroupKey(
                                "ordered_at",
                                new FieldDatetime(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new PlacedAtColumn().Name.TextValue
                                )
                            ),
                            new GroupKey(
                                "status",
                                new FieldString(
                                    new JoinedString(
                                        new DotString(),
                                        [
                                            new RelationalSchemaWithForeignKeys().Name,
                                            new OrdersTable().Name,
                                        ]
                                    ).TextValue,
                                    new OrderStatusColumn().Name.TextValue
                                )
                            ),
                        ],
                        having: new GreaterThanOrEqualDatetimeGroup(
                            new KeyDatetime("ordered_at"),
                            new StartOfMonthDatetimeGroup(
                                new LiteralDatetime(
                                    new DateTimeOffset(2024, 7, 1, 9, 0, 0, TimeSpan.Zero)
                                ),
                                zone: new LiteralString("Pacific/Pago_Pago")
                            )
                        ),
                        select:
                        [
                            new SelectItemGroup("status", new KeyString("status")),
                            new SelectItemGroup(
                                "local_hour_start_of_the_key",
                                new StartOfHourDatetimeGroup(
                                    new KeyDatetime("ordered_at"),
                                    zone: new LiteralString("Pacific/Pago_Pago")
                                )
                            ),
                            new SelectItemGroup(
                                "local_week_of_the_last_order",
                                new StartOfWeekDatetimeGroup(
                                    new MaxDatetimeGroup(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        )
                                    ),
                                    zone: new LiteralString("Europe/Moscow")
                                )
                            ),
                            new SelectItemGroup(
                                "local_days",
                                new CountDistinctGroup(
                                    new StartOfDayDatetimeRow(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        ),
                                        zone: new LiteralString("Pacific/Pago_Pago")
                                    )
                                )
                            ),
                            new SelectItemGroup(
                                "latest_local_month",
                                new MaxDatetimeGroup(
                                    new StartOfMonthDatetimeRow(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        ),
                                        zone: new LiteralString("Pacific/Pago_Pago")
                                    )
                                )
                            ),
                        ]
                    )
                ),
                new SubqueryQuery(
                    "totals",
                    new TotalQuery(
                        from: new FromEntity(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new OrdersTable().Name,
                                ]
                            ).TextValue
                        ),
                        where: new GreaterThanOrEqualDatetimeRow(
                            new FieldDatetime(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new OrdersTable().Name,
                                    ]
                                ).TextValue,
                                new PlacedAtColumn().Name.TextValue
                            ),
                            new StartOfQuarterDatetimeRow(
                                new LiteralDatetime(
                                    new DateTimeOffset(2024, 7, 1, 9, 0, 0, TimeSpan.Zero)
                                ),
                                zone: new LiteralString("Pacific/Pago_Pago")
                            )
                        ),
                        aggregate:
                        [
                            new SelectItemTotal(
                                "orders_this_local_quarter",
                                new CountTotal()
                            ),
                            new SelectItemTotal(
                                "local_days_with_orders",
                                new CountDistinctTotal(
                                    new StartOfDayDatetimeRow(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        ),
                                        zone: new LiteralString("Pacific/Pago_Pago")
                                    )
                                )
                            ),
                            new SelectItemTotal(
                                "local_month_of_the_first_order",
                                new StartOfMonthDatetimeNullableTotal(
                                    new MinDatetimeNullableTotal(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        )
                                    ),
                                    zone: new LiteralString("Pacific/Pago_Pago")
                                )
                            ),
                            new SelectItemTotal(
                                "busiest_local_day",
                                new ModeDatetimeNullableTotal(
                                    new StartOfDayDatetimeRow(
                                        new FieldDatetime(
                                            new JoinedString(
                                                new DotString(),
                                                [
                                                    new RelationalSchemaWithForeignKeys().Name,
                                                    new OrdersTable().Name,
                                                ]
                                            ).TextValue,
                                            new PlacedAtColumn().Name.TextValue
                                        ),
                                        zone: new LiteralString("Pacific/Pago_Pago")
                                    )
                                )
                            ),
                        ]
                    )
                ),
            ],
            from: new FromSubquery("by_hour"),
            joins: [new JoinSubquery(JoinKind.Inner, "totals", new LiteralBoolean(true))],
            select:
            [
                new SelectItemProjection("status", new FieldString("by_hour", "status")),
                new SelectItemProjection(
                    "hour_start",
                    new FieldDatetime("by_hour", "local_hour_start_of_the_key")
                ),
                new SelectItemProjection(
                    "orders_this_local_quarter",
                    new FieldInteger("totals", "orders_this_local_quarter")
                ),
            ]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, in no particular order.
    /// Local times are read with the tz database of PostgreSQL 17 and checked with
    /// Python zoneinfo; no value falls in a skipped or repeated local hour.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("status"), new StringColumnType()),
                    new Column(new String("hour_start"), new DateTimeColumnType()),
                    new Column(
                        new String("orders_this_local_quarter"),
                        new LongColumnType()
                    ),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("status"), new StringColumnType()),
                                new InvariantCell(new String("cancelled"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hour_start"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(4),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
                                        new Time(
                                            new UShort(13),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("orders_this_local_quarter"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(6))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("status"), new StringColumnType()),
                                new InvariantCell(new String("pending"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hour_start"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(2),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
                                        new Time(
                                            new UShort(11),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("orders_this_local_quarter"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(6))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("status"), new StringColumnType()),
                                new InvariantCell(new String("pending"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hour_start"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(6),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
                                        new Time(
                                            new UShort(15),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("orders_this_local_quarter"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(6))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("status"), new StringColumnType()),
                                new InvariantCell(new String("shipped"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hour_start"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(3),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
                                        new Time(
                                            new UShort(12),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("orders_this_local_quarter"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(6))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
                        [
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("status"), new StringColumnType()),
                                new InvariantCell(new String("shipped"))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("hour_start"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(5),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
                                        new Time(
                                            new UShort(14),
                                            new UShort(0),
                                            new UShort(0)
                                        )
                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("orders_this_local_quarter"),
                                    new LongColumnType()
                                ),
                                new InvariantCell(new Long(6))
                            ),
                        ],
                        pair => pair.Key,
                        pair => pair.Value,
                        column => new ColumnHash(column)
                    )
                ),
            ]
        );
}
