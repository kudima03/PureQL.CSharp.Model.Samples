namespace PureQL.CSharp.Model.Samples.Queries.Where.Each;

public sealed record EachOrOfDateTimeAddSecondsEqualsTargetAndDateTimeDiffSecondsAboveZeroQuery
{
    public Query Value =>
        new Query(
            new FromExpression(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new UsersTable().Name]
                ).TextValue
            ),
            [
                new SelectExpression(
                    new ArrayReturning(
                        new UuidArrayReturning(
                            new UuidField(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new UsersTable().Name,
                                    ]
                                ).TextValue,
                                new UserIdColumn().Name.TextValue
                            )
                        )
                    )
                ),
            ],
            new BooleanArrayReturning(
                new EachOrOperator([
                    new BooleanArrayReturning(
                        new EachEquality(
                            new EachDateTimeEquality(
                                new DateTimeArrayReturning(
                                    new EachDateTimeAddSeconds(
                                        new DateTimeArrayReturning(
                                            new DateTimeField(
                                                new JoinedString(
                                                    new DotString(),
                                                    [
                                                        new RelationalSchemaWithForeignKeys().Name,
                                                        new UsersTable().Name,
                                                    ]
                                                ).TextValue,
                                                new LastLoginColumn().Name.TextValue
                                            )
                                        ),
                                        new NumberReturning(new NumberScalar(3600))
                                    )
                                ),
                                new DateTimeReturning(
                                    new DateTimeScalar(new DateTime(2024, 6, 1, 9, 30, 0))
                                )
                            )
                        )
                    ),
                    new BooleanArrayReturning(
                        new EachComparison(
                            new EachNumberComparison(
                                EachComparisonOperator.EachGreaterThan,
                                new NumberArrayReturning(
                                    new EachDateTimeDiffSeconds(
                                        new DateTimeArrayReturning(
                                            new DateTimeField(
                                                new JoinedString(
                                                    new DotString(),
                                                    [
                                                        new RelationalSchemaWithForeignKeys().Name,
                                                        new UsersTable().Name,
                                                    ]
                                                ).TextValue,
                                                new LastLoginColumn().Name.TextValue
                                            )
                                        ),
                                        new DateTimeReturning(
                                            new DateTimeScalar(
                                                new DateTime(2024, 6, 2, 0, 0, 0)
                                            )
                                        )
                                    )
                                ),
                                new NumberReturning(new NumberScalar(0))
                            )
                        )
                    ),
                ])
            ),
            join: null,
            groupBy: null,
            having: null,
            orderBy: null,
            pagination: null
        );
}
