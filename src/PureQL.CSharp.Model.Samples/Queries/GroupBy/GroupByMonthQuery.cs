/// <summary>
/// Selects from schema_with_foreign_keys.users, where signup_date is at least startOfYear
/// of 2020-06-15, grouped by startOfMonth of signup_date as the date key signup_month:
/// the key, the count of users, the sum of user_age, and startOfHour of the max
/// last_login, ordered by signup_month.
/// </summary>
public sealed record GroupByMonthQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public PureQLQuery Value =>
        new MainGroupedQueryWithoutPagination(
            from: new FromEntity(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithForeignKeys().Name, new UsersTable().Name]
                ).TextValue
            ),
            where: new GreaterThanOrEqualDateRow(
                new FieldDate(
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithForeignKeys().Name,
                            new UsersTable().Name,
                        ]
                    ).TextValue,
                    new SignupDateColumn().Name.TextValue
                ),
                new StartOfYearDateRow(new LiteralDate(new DateOnly(2020, 6, 15)))
            ),
            groupBy:
            [
                new GroupKey(
                    "signup_month",
                    new StartOfMonthDateRow(
                        new FieldDate(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new SignupDateColumn().Name.TextValue
                        )
                    )
                ),
            ],
            select:
            [
                new SelectItemGroup("signup_month", new KeyDate("signup_month")),
                new SelectItemGroup("signups", new CountGroup()),
                new SelectItemGroup(
                    "total_age",
                    new SumDecimalGroup(
                        new FieldDecimal(
                            new JoinedString(
                                new DotString(),
                                [
                                    new RelationalSchemaWithForeignKeys().Name,
                                    new UsersTable().Name,
                                ]
                            ).TextValue,
                            new UserAgeColumn().Name.TextValue
                        )
                    )
                ),
                new SelectItemGroup(
                    "last_login_hour",
                    new StartOfHourDatetimeGroup(
                        new MaxDatetimeGroup(
                            new FieldDatetime(
                                new JoinedString(
                                    new DotString(),
                                    [
                                        new RelationalSchemaWithForeignKeys().Name,
                                        new UsersTable().Name,
                                    ]
                                ).TextValue,
                                new LastLoginColumn().Name.TextValue
                            )
                        )
                    )
                ),
            ],
            orderBy: [new OrderItemGroupExpression(new KeyDate("signup_month"))]
        );

    /// <summary>
    /// The rows the query returns under the PureQL specification's semantics over
    /// <see cref="SchemaDataSetWithForeignKeys"/> and
    /// <see cref="AuditSchemaDataSet"/>, in this order.
    /// </summary>
    public IStoredTableDataSet Result =>
        new StoredTableDataSet(
            new Table(
                new EmptyString(),
                [
                    new Column(new String("signup_month"), new DateColumnType()),
                    new Column(new String("signups"), new LongColumnType()),
                    new Column(new String("total_age"), new DoubleColumnType()),
                    new Column(new String("last_login_hour"), new DateTimeColumnType()),
                ],
                []
            ),
            [
                new Row(
                    new Dictionary<KeyValuePair<IColumn, ICell>, IColumn, ICell>(
