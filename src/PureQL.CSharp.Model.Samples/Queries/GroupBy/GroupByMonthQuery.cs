                                    )
                                )
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(new String("signups"), new LongColumnType()),
                                new InvariantCell(new Long(2))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("total_age"),
                                    new DoubleColumnType()
                                ),
                                new InvariantCell(new Double(58))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("last_login_hour"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(1),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
