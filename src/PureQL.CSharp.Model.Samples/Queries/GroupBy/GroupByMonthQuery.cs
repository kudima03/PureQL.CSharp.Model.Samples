                                new InvariantCell(new Double(25))
                            ),
                            new KeyValuePair<IColumn, ICell>(
                                new Column(
                                    new String("last_login_hour"),
                                    new DateTimeColumnType()
                                ),
                                new UtcDateTimeCell(
                                    new DateTime(
                                        new Date(
                                            new UShort(4),
                                            new UShort(6),
                                            new UShort(2024)
                                        ),
