/// <summary>
/// Selects need.id as ownId from schema_with_indexes.table_with_indexes (aliased need),
/// inner-joined to schema_with_indexes.table_with_single_index on
/// table_with_indexes.tenant_id equals table_with_single_index.id.
/// </summary>
public sealed record FromAliasReferenceToCollidingColumnQuery
{
    /// <summary>Builds the query afresh on every read.</summary>
    public Query Value =>
        new Query(
            new FromExpression(
                new JoinedString(
                    new DotString(),
                    [new RelationalSchemaWithIndexes().Name, new TableWithIndexes().Name]
                ).TextValue,
                "need"
            ),
            [
                new SelectExpression(
                    new ArrayReturning(
                        new UuidArrayReturning(
                            new UuidField("need", new IdColumn().Name.TextValue)
                        )
                    ),
                    "ownId"
                ),
            ],
            where: null,
            [
                new Join(
                    JoinType.Inner,
                    new JoinedString(
                        new DotString(),
                        [
                            new RelationalSchemaWithIndexes().Name,
                            new TableWithSingleIndex().Name,
                        ]
                    ).TextValue,
                    new BooleanArrayReturning(
                        new EachEquality(
                            new EachUuidEquality(
                                new UuidArrayReturning(
                                    new UuidField(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithIndexes().Name,
                                                new TableWithIndexes().Name,
                                            ]
                                        ).TextValue,
                                        new TenantIdColumn().Name.TextValue
                                    )
                                ),
                                new UuidArrayReturning(
                                    new UuidField(
                                        new JoinedString(
                                            new DotString(),
                                            [
                                                new RelationalSchemaWithIndexes().Name,
                                                new TableWithSingleIndex().Name,
                                            ]
                                        ).TextValue,
                                        new IdColumn().Name.TextValue
                                    )
                                )
                            )
                        )
                    )
                ),
            ],
            groupBy: null,
            having: null,
            orderBy: null,
            pagination: null
        );

